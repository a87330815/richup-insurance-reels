def collect(cfg):
    """계정 설정에 따라 켜진 (level, pattern, why) 목록."""
    rules = []
    for name in cfg.get("rule_presets", []):
        if name not in PRESETS:
            raise SystemExit(f"없는 검수 프리셋: {name} (있는 것: {', '.join(PRESETS)})")
        for lv in ("block", "warn"):
            rules += [(lv, p, w) for p, w in PRESETS[name][lv]]
    own = cfg.get("compliance", {})
    for lv in ("block", "warn"):
        rules += [(lv, p, w) for p, w in own.get(lv, [])]
    return rules
